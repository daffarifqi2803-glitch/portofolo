function getTagDotColor($tag) {
    $t = strtolower($tag);
    if (strpos($t, 'php') !== false || strpos($t, 'laravel') !== false) return '#ef4444'; // Red
    if (strpos($t, 'mysql') !== false || strpos($t, 'sql') !== false || strpos($t, 'database') !== false || strpos($t, 'postgres') !== false) return '#3b82f6'; // Blue
    if (strpos($t, 'android') !== false || strpos($t, 'vue') !== false || strpos($t, 'leaf') !== false || strpos($t, 'whatsapp') !== false) return '#10b981'; // Green
    if (strpos($t, 'firebase') !== false || strpos($t, 'fcm') !== false || strpos($t, 'js') !== false || strpos($t, 'javascript') !== false) return '#f59e0b'; // Amber
    if (strpos($t, 'tailwind') !== false || strpos($t, 'css') !== false || strpos($t, 'bootstrap') !== false) return '#06b6d4'; // Cyan
    if (strpos($t, 'react') !== false || strpos($t, 'node') !== false) return '#38bdf8'; // Sky blue
    if (strpos($t, 'figma') !== false || strpos($t, 'design') !== false) return '#a855f7'; // Purple
    return '#8b5cf6'; // Default purple
}

